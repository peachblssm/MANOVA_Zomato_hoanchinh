# a) Kiểm định chuẩn đa biến Henze-Zirkler (HZ)
# Hàm pg.multivariate_normality của pingouin chính là kiểm định HZ, nhưng tạo ma trận n x n
# nên bị tràn bộ nhớ với nhóm Tối (16.132 dòng) và Khuya (12.184 dòng).
# Hàm dưới đây tính đúng công thức HZ của pingouin nhưng chia nhỏ ma trận thành từng khối.
print("\na) Kiểm định chuẩn đa biến Henze-Zirkler (HZ)")
print("-" * 50)

def hz_test(X, block=2000):
    X = np.asarray(X, dtype=float)
    n, p_ = X.shape
    S = np.cov(X, rowvar=False, bias=True)
    S_inv_ = np.linalg.pinv(S, hermitian=True)
    d = X - X.mean(axis=0)
    Dj = np.sum(d @ S_inv_ * d, axis=1)                 # D² Mahalanobis của từng quan sát
    XS = X @ S_inv_
    Y_diag = np.sum(XS * X, axis=1)
    b = 1 / np.sqrt(2) * ((2 * p_ + 1) / 4) ** (1 / (p_ + 4)) * n ** (1 / (p_ + 4))
    tong = 0.0
    for s in range(0, n, block):                         # tính Djk theo từng khối dòng
        Djk = -2 * (XS[s:s + block] @ X.T) + Y_diag[s:s + block, None] + Y_diag[None, :]
        tong += np.exp(-(b ** 2) / 2 * Djk).sum()
    hz = n * (tong / n ** 2
              - 2 * (1 + b ** 2) ** (-p_ / 2) * np.mean(np.exp(-(b ** 2 / (2 * (1 + b ** 2))) * Dj))
              + (1 + 2 * b ** 2) ** (-p_ / 2))
    # p-value theo phân phối lognormal (giống pingouin)
    wb = (1 + b ** 2) * (1 + 3 * b ** 2)
    a = 1 + 2 * b ** 2
    mu = 1 - a ** (-p_ / 2) * (1 + p_ * b ** 2 / a + (p_ * (p_ + 2) * b ** 4) / (2 * a ** 2))
    si2 = (2 * (1 + 4 * b ** 2) ** (-p_ / 2)
           + 2 * a ** (-p_) * (1 + (2 * p_ * b ** 4) / a ** 2 + (3 * p_ * (p_ + 2) * b ** 8) / (4 * a ** 4))
           - 4 * wb ** (-p_ / 2) * (1 + (3 * p_ * b ** 4) / (2 * wb) + (p_ * (p_ + 2) * b ** 8) / (2 * wb ** 2)))
    pmu = np.log(np.sqrt(mu ** 4 / (si2 + mu ** 2)))
    psi = np.sqrt(np.log1p(si2 / mu ** 2))
    pval = stats.lognorm.sf(hz, psi, scale=np.exp(pmu))
    return hz, pval

hz_results = []
for slot in order_slot:
    subset = df[df['Khung_gio'] == slot][X_vars]
    sk = stats.skew(subset, axis=0)
    ku = stats.kurtosis(subset, axis=0, fisher=True)
    n_i = len(subset)
    hz, pval = hz_test(subset.values)
    hz_results.append({
        'Nhóm': slot,
        'n': n_i,
        'HZ statistic': round(hz, 4),
        'p-value': round(pval, 6),
        'Normal?': pval > 0.05,
        'Max |skew|': round(np.max(np.abs(sk)), 3),
        'Max kurtosis': round(np.max(ku), 3)
    })

hz_df = pd.DataFrame(hz_results)
