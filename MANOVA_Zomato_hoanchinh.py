# b) Box's M Test
# pg.box_m tính M dưới dạng tích lũy thừa nên bị tràn số (trả về NaN) khi cỡ mẫu lớn,
# vì vậy tính trực tiếp theo công thức logarit:
# M = (N - g)·ln|Sp| - Σ(ni - 1)·ln|Si|
print("\nb) Box's M Test (Homogeneity of Covariance Matrices)")
print("-" * 50)

n_list = []
S_list = []
for slot in order_slot:
    subset = df[df['Khung_gio'] == slot][X_vars]
    n_list.append(len(subset))
    S_list.append(subset.cov().values)

S_pooled = sum((n_i - 1) * S_i for n_i, S_i in zip(n_list, S_list)) / (N - g)
logdet_Sp = np.linalg.slogdet(S_pooled)[1]
logdet_Si = [np.linalg.slogdet(S_i)[1] for S_i in S_list]
M_box = (N - g) * logdet_Sp - sum((n_i - 1) * ld for n_i, ld in zip(n_list, logdet_Si))
c_box = (sum(1 / (n_i - 1) for n_i in n_list) - 1 / (N - g)) * (2 * p**2 + 3 * p - 1) / (6 * (p + 1) * (g - 1))
chi2_box = M_box * (1 - c_box)
df_box = p * (p + 1) * (g - 1) / 2
pval_box = stats.chi2.sf(chi2_box, df_box)

boxm = pd.DataFrame({'Box M': [M_box], 'Chi2': [chi2_box], 'df': [df_box],
                     'pval': [pval_box], 'equal_cov': [pval_box > 0.05]}, index=['box'])
print(boxm)
print("\nln|Si| theo từng nhóm:", {slot: round(float(ld), 3) for slot, ld in zip(order_slot, logdet_Si)})
print(f"ln|Sp| (ma trận gộp) = {logdet_Sp:.3f}")

if pval_box < 0.05:
    print("→ p < 0.05 → Bác bỏ H0 đồng nhất Σ. Chọn Pillai's Trace làm tiêu chuẩn chính.")
else:
    print("→ p ≥ 0.05 → Không bác bỏ H0. Có thể dùng Wilks' Lambda.")

