# (ví dụ "0.458333333") không có dấu ':' sẽ trả về NaN và bị loại ở bước dropna
def parse_hour(x):
    """Chuyển Time_Orderd thành giờ nguyên (0-23)"""
    if pd.isna(x):
        return np.nan
    try:
        # Nếu là chuỗi dạng HH:MM
        if isinstance(x, str) and ':' in x:
            return int(x.split(':')[0])
        # Nếu là số thập phân (ví dụ 0.458333333 = 11:00)
        elif isinstance(x, (int, float)):
            # Một số giá trị là fraction của ngày
            if 0 <= x < 1:
                return int(x * 24)
            else:
                return int(x)
        else:
            return np.nan
    except:
        return np.nan

